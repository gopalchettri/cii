    "product, version,\n"
    "   vulnerability, user, integration, regulation, control or business process. A claim about "
    "the real world (who\n"
    "   did this before, what happened, what it caused) comes ONLY from the EVIDENCE block's "
    "facts: never invent an\n"
    "   incident, name, date or amount. Generic believable steps (a phishing email, "
    "reconnaissance) are allowed; where\n"
    "   no evidence backs a step, keep it plainly hypothetical.\n"
