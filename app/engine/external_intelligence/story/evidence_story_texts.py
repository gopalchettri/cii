    "    asset are written side by side and must not open alike), and let it lead naturally into "
    "the attack.\n"
    "17. SPECIFIC. Name the component, interface or data the attacker acts on and what it does "
    "there, step by step;\n"
    '    never a generic line such as "an attacker may exploit vulnerabilities" or "unauthorised '
